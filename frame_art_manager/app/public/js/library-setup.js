// First-run library setup: connect an empty library folder to a GitHub repo.
// Talks to routes/setup.js. Shown on its own only when the library folder is not a
// git repo and holds nothing but the app's startup skeleton; a folder that is already
// a repo never sees it. Advanced > Settings > Library Sync opens it any time the
// library is not connected, including one that has been used without sync, and
// offers Disconnect while it is. Both show the GitHub connection (GET connection):
// the key, whether GitHub is reachable and knows the key, and for a connected
// library how its sync stands.
(function () {
  const SETUP_API = 'api/setup';
  const DISMISS_KEY = 'frameArt.librarySetupDismissed';
  const REPO_PATTERN = /^[A-Za-z0-9-]{1,39}\/[A-Za-z0-9._-]{1,100}$/;
  const POLL_MS = 2000;
  // While setup waits for the deploy key, the connection is re-checked on its own.
  const CONNECTION_POLL_MS = 8000;
  const CONNECTION_POLL_LIMIT_MS = 15 * 60 * 1000;

  let status = null;
  let testedRepo = null; // repo the last successful test was for
  let polling = null;
  let connection = null; // last GET connection answer
  let connectionChecking = false;
  let connectionRequest = 0;
  let connectionPoll = null;
  let connectionPollStartedAt = 0;
  let autoTestedRepo = null; // repo setup tested on its own after filling it in

  const el = (id) => document.getElementById(id);

  function normalizeRepo(value) {
    return String(value || '').trim().replace(/\.git$/, '');
  }

  function isValidRepo(repo) {
    if (!REPO_PATTERN.test(repo) || repo.includes('..')) return false;
    const name = repo.split('/')[1];
    return !name.startsWith('.') && !name.startsWith('-');
  }

  function isDismissed() {
    try { return localStorage.getItem(DISMISS_KEY) === '1'; } catch { return false; }
  }

  function setDismissed(value) {
    try {
      if (value) localStorage.setItem(DISMISS_KEY, '1');
      else localStorage.removeItem(DISMISS_KEY);
    } catch { /* storage unavailable: the screen just shows again next time */ }
  }

  function setResult(target, kind, message, detail) {
    target.className = `library-setup-result ${kind ? `library-setup-result-${kind}` : ''}`;
    target.textContent = '';
    if (!message) return;
    const text = document.createElement('div');
    text.textContent = message;
    target.appendChild(text);
    if (detail) {
      const pre = document.createElement('pre');
      pre.textContent = detail;
      target.appendChild(pre);
    }
  }

  function openOverlay() {
    el('library-setup').classList.remove('hidden');
    document.body.classList.add('library-setup-open');
    refreshConnection().then(startConnectionPolling);
  }

  function closeOverlay() {
    el('library-setup').classList.add('hidden');
    document.body.classList.remove('library-setup-open');
    stopConnectionPolling();
  }

  function isOverlayOpen() {
    return !el('library-setup').classList.contains('hidden');
  }

  // --- GitHub connection ---------------------------------------------------------

  function timeAgo(iso) {
    const then = new Date(iso).getTime();
    if (!iso || Number.isNaN(then)) return 'unknown';
    const seconds = Math.max(0, Math.round((Date.now() - then) / 1000));
    if (seconds < 60) return 'just now';
    const minutes = Math.round(seconds / 60);
    if (minutes < 60) return `${minutes} minute${minutes === 1 ? '' : 's'} ago`;
    const hours = Math.round(minutes / 60);
    if (hours < 48) return `${hours} hour${hours === 1 ? '' : 's'} ago`;
    const days = Math.round(hours / 24);
    return `${days} days ago`;
  }

  function plural(count, word) {
    return `${count} ${word}${count === 1 ? '' : 's'}`;
  }

  /** Same rule as describeKeyMatch() in library_setup.js, for the repository typed into setup. */
  function keyMismatch(github, repo) {
    if (!github || github.state !== 'deploy_key' || !repo) return null;
    if (github.identity.toLowerCase() === repo.toLowerCase()) return null;
    return `This add-on's key is a deploy key on ${github.identity}, not on ${repo}. GitHub allows a deploy key ` +
      `on one repository only: delete it from ${github.identity}'s deploy keys, then add it to ${repo}.`;
  }

  /**
   * Rows for the connection list: {kind: ok|warn|error|pending|info, label, text, detail?}.
   * forSetup: the setup screen, where a key GitHub does not know yet is the expected
   * next step (warn), and the repository to match is the one typed in.
   */
  function connectionRows(data, { forSetup }) {
    const rows = [];
    const keySource = data ? data.keySource : (status && status.keySource);
    if (keySource === 'generated') {
      rows.push({ kind: 'ok', label: 'SSH key', text: 'Generated by this add-on' });
    } else if (keySource === 'config') {
      rows.push({ kind: 'ok', label: 'SSH key', text: 'From the add-on configuration (ssh_private_key)' });
    } else if (data && data.github.recognized) {
      // Not run through run.sh (a container with its own ssh setup): the key works, wherever it is.
      rows.push({ kind: 'ok', label: 'SSH key', text: 'From this system\'s ssh setup' });
    } else {
      rows.push({ kind: 'error', label: 'SSH key', text: 'None. Restart the add-on to generate one.' });
    }

    if (!data) {
      rows.push({ kind: 'pending', label: 'GitHub', text: 'Checking…' });
      return rows;
    }
    const github = data.github;
    if (!github.reachable) {
      rows.push({ kind: 'error', label: 'GitHub', text: github.message, detail: github.detail });
      return rows;
    }
    rows.push({ kind: 'ok', label: 'GitHub', text: 'Reachable' });

    if (github.state === 'deploy_key') {
      rows.push({ kind: 'ok', label: 'Key recognized', text: `Yes, deploy key on ${github.identity}` });
    } else if (github.state === 'account_key') {
      rows.push({ kind: 'ok', label: 'Key recognized', text: `Yes, account key of ${github.identity}` });
    } else if (forSetup) {
      rows.push({ kind: 'warn', label: 'Key recognized', text: 'Not yet. Add it to the repository as a deploy key (step 2).' });
    } else if (!data.isRepo) {
      rows.push({ kind: 'warn', label: 'Key recognized', text: 'Not yet. Set up GitHub sync to add it to a repository.' });
    } else {
      rows.push({
        kind: 'error',
        label: 'Key recognized',
        text: 'No. GitHub does not know this key, so sync cannot work. Add it to the repository as a deploy key with write access.'
      });
    }

    const mismatch = forSetup
      ? keyMismatch(github, normalizeRepo(el('library-setup-repo').value))
      : (data.keyMatch && !data.keyMatch.ok ? data.keyMatch.message : null);
    if (mismatch) rows.push({ kind: 'error', label: 'Repository', text: mismatch });

    const sync = data.sync;
    if (!forSetup && sync) {
      if (sync.ahead > 0) {
        rows.push({ kind: 'warn', label: 'Waiting to upload', text: `${plural(sync.ahead, 'commit')} not on GitHub yet` });
      } else if (sync.ahead === 0) {
        rows.push({ kind: 'ok', label: 'Waiting to upload', text: 'Nothing, everything is on GitHub' });
      }
      if (sync.uncommitted > 0) {
        rows.push({ kind: 'info', label: 'Not saved yet', text: `${plural(sync.uncommitted, 'file')} changed since the last sync` });
      }
      rows.push({ kind: 'info', label: 'Last upload', text: sync.lastPush ? timeAgo(sync.lastPush) : 'None from this add-on yet' });
      if (sync.lastFetch) rows.push({ kind: 'info', label: 'Last check for changes', text: timeAgo(sync.lastFetch) });
      if (sync.failure) {
        rows.push({
          kind: 'error',
          label: 'Last sync failed',
          text: `${timeAgo(sync.failure.timestamp)}, and none has worked since.`,
          detail: sync.failure.message
        });
      }
    }
    return rows;
  }

  const ROW_ICONS = { ok: '✓', warn: '!', error: '✕', pending: '…', info: '•' };

  function renderConnectionList(listId, options) {
    const list = el(listId);
    if (!list) return;
    list.textContent = '';
    for (const row of connectionRows(connection, options)) {
      const item = document.createElement('li');
      item.className = `github-connection-row github-connection-${row.kind}`;
      const icon = document.createElement('span');
      icon.className = 'github-connection-icon';
      icon.setAttribute('aria-hidden', 'true');
      icon.textContent = ROW_ICONS[row.kind];
      const body = document.createElement('div');
      const label = document.createElement('strong');
      label.textContent = `${row.label}: `;
      body.appendChild(label);
      body.appendChild(document.createTextNode(row.text));
      if (row.detail) {
        const pre = document.createElement('pre');
        pre.textContent = row.detail;
        body.appendChild(pre);
      }
      item.appendChild(icon);
      item.appendChild(body);
      list.appendChild(item);
    }
  }

  function renderConnection() {
    renderConnectionList('library-setup-connection', { forSetup: true });
    renderConnectionList('library-sync-connection', { forSetup: false });
    ['library-setup-check-btn', 'library-sync-check-btn'].forEach((id) => {
      const button = el(id);
      if (!button) return;
      button.disabled = connectionChecking;
      button.textContent = connectionChecking ? 'Checking…' : 'Check again';
    });
    if (status) updateRepoDependentUi();
  }

  async function refreshConnection({ fresh = false } = {}) {
    const request = ++connectionRequest;
    connectionChecking = true;
    renderConnection();
    try {
      const query = new URLSearchParams();
      if (fresh) query.set('fresh', '1');
      const response = await fetch(`${SETUP_API}/connection?${query}`);
      if (!response.ok) throw new Error(`status ${response.status}`);
      const data = await response.json();
      if (request !== connectionRequest) return;
      connection = data;
    } catch (error) {
      console.warn('GitHub connection check failed:', error.message);
    } finally {
      if (request === connectionRequest) {
        connectionChecking = false;
        renderConnection();
        onConnectionChecked();
      }
    }
  }

  /**
   * On the setup screen, a deploy key GitHub reports names the repository: setup uses it
   * and tests it. Only an account key (ssh_private_key), which reaches every repository of
   * its account, needs the repository typed in.
   */
  function onConnectionChecked() {
    updateRepoDependentUi();
    if (!connection || !connection.github.recognized) return;
    stopConnectionPolling();
    if (!isOverlayOpen() || connection.github.state !== 'deploy_key' || isJobRunning()) return;
    const input = el('library-setup-repo');
    const typed = normalizeRepo(input.value);
    const found = connection.github.identity;
    if (typed !== found) {
      input.value = found;
      resetTest();
    }
    if (autoTestedRepo !== found && testedRepo !== found) {
      autoTestedRepo = found;
      testConnection();
    }
  }

  function startConnectionPolling() {
    if (connectionPoll || !isOverlayOpen() || (connection && connection.github.recognized)) return;
    connectionPollStartedAt = Date.now();
    connectionPoll = setInterval(() => {
      if (!isOverlayOpen() || Date.now() - connectionPollStartedAt > CONNECTION_POLL_LIMIT_MS) {
        stopConnectionPolling();
        return;
      }
      if (document.hidden || connectionChecking) return;
      refreshConnection({ fresh: true });
    }, CONNECTION_POLL_MS);
  }

  function stopConnectionPolling() {
    if (connectionPoll) clearInterval(connectionPoll);
    connectionPoll = null;
  }

  function isSettingsTabShown() {
    return /^#\/advanced\/settings\b/.test(window.location.hash);
  }

  function resetTest() {
    testedRepo = null;
    setResult(el('library-setup-test-result'), '', '');
    el('library-setup-connect-hint').textContent = 'Test the connection first.';
    updateRepoDependentUi();
  }

  function needsTypedRepo() {
    return Boolean(connection && connection.github.state === 'account_key');
  }

  function updateRepoDependentUi() {
    const repo = normalizeRepo(el('library-setup-repo').value);
    const valid = isValidRepo(repo);
    const manual = needsTypedRepo();
    el('library-setup-repo-manual').classList.toggle('hidden', !manual);
    const label = el('library-setup-repo-label');
    label.textContent = valid ? repo : '';
    label.classList.toggle('hidden', manual || !valid);
    const waiting = el('library-setup-repo-waiting');
    waiting.classList.toggle('hidden', manual || valid);
    waiting.textContent = 'found once the key is added on GitHub…';
    el('library-setup-repo-error').textContent =
      repo && !valid ? 'Use the form owner/name, for example your-user/frame_art.' : '';
    // Before the repository is known, Test asks GitHub again which repository the key is on.
    el('library-setup-test').disabled = (manual && !valid) || isJobRunning() || (!valid && connectionChecking);
    const canConnect = Boolean(status && status.canConnect) && testedRepo === repo && !isJobRunning();
    el('library-setup-connect').disabled = !canConnect;
  }

  function isJobRunning() {
    return Boolean(status && status.connectJob && status.connectJob.status === 'running');
  }

  function renderKey() {
    const keyBox = el('library-setup-key-box');
    const note = el('library-setup-key-note');
    if (status.publicKey) {
      el('library-setup-key').value = status.publicKey;
      keyBox.classList.remove('hidden');
      note.textContent = '';
    } else {
      keyBox.classList.add('hidden');
      note.textContent = status.keySource === 'config'
        ? 'This add-on uses the SSH key from its configuration (ssh_private_key). Add the public half of that key as the deploy key.'
        : 'No SSH key is available. Restart the add-on to generate one, then reopen this screen.';
    }
  }

  function render() {
    el('library-setup-path').textContent = status.frameArtPath || '';
    const existing = el('library-setup-existing');
    if (status.hasLocalFiles) {
      const images = status.imageCount === 1 ? '1 image' : `${status.imageCount} images`;
      existing.textContent = `This library already has ${images}. Connect an empty repository to upload ` +
        'the library to it; nothing here is moved or deleted. A repository that already holds a library ' +
        'can only be connected to an empty library folder.';
      existing.classList.remove('hidden');
    } else {
      existing.textContent = '';
      existing.classList.add('hidden');
    }
    renderKey();
    renderJob();
    updateRepoDependentUi();
  }

  function renderJob() {
    const job = status.connectJob;
    const progress = el('library-setup-progress');
    if (!job) return;
    if (job.repo && !el('library-setup-repo').value) {
      el('library-setup-repo').value = job.repo;
    }
    if (job.status === 'running') {
      setResult(progress, 'pending', `${job.step || 'Working'}…`);
    } else if (job.status === 'failed') {
      setResult(progress, 'error', 'Connecting the library failed.', job.message);
    } else if (job.status === 'succeeded') {
      setResult(progress, job.warning ? 'warning' : 'success',
        job.warning ? `${job.message} ${job.warning}` : `${job.message} Reloading…`);
    }
  }

  async function fetchStatus() {
    const response = await fetch(`${SETUP_API}/status`);
    if (!response.ok) throw new Error(`Setup status failed (${response.status})`);
    status = await response.json();
    return status;
  }

  async function postJson(path, body) {
    const response = await fetch(`${SETUP_API}/${path}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body)
    });
    let data = {};
    try { data = await response.json(); } catch { /* non-JSON error page */ }
    return { response, data };
  }

  async function testConnection() {
    const repo = normalizeRepo(el('library-setup-repo').value);
    const result = el('library-setup-test-result');
    if (!isValidRepo(repo) && !needsTypedRepo()) {
      setResult(result, 'pending', 'Asking GitHub which repository the key is on…');
      await refreshConnection({ fresh: true }); // fills in the repository and tests it, once GitHub knows the key
      if (!isValidRepo(normalizeRepo(el('library-setup-repo').value))) {
        const github = connection && connection.github;
        setResult(result, 'error', github && github.reachable
          ? 'GitHub does not know the key yet. Add it as a deploy key (step 2), then test again.'
          : (github ? github.message : 'Could not check the connection.'));
      }
      return;
    }
    testedRepo = null;
    el('library-setup-test').disabled = true;
    updateRepoDependentUi();
    setResult(result, 'pending', 'Testing…');
    try {
      const { data } = await postJson('test', { repo });
      if (data.success) {
        testedRepo = repo;
        setResult(result, 'success', data.message);
        let hint = 'The repository has a library: it will be downloaded into this add-on.';
        if (data.state === 'empty') {
          hint = status.imageCount > 0
            ? 'The repository is empty: this library will be uploaded to it.'
            : 'The repository is empty: a new library will be created in it.';
        }
        el('library-setup-connect-hint').textContent = hint;
      } else {
        setResult(result, 'error', data.message || 'The test failed.', data.detail);
      }
    } catch (error) {
      setResult(result, 'error', `The test failed: ${error.message}`);
    } finally {
      updateRepoDependentUi();
    }
  }

  async function connectLibrary() {
    const repo = normalizeRepo(el('library-setup-repo').value);
    const progress = el('library-setup-progress');
    el('library-setup-connect').disabled = true;
    el('library-setup-test').disabled = true;
    setResult(progress, 'pending', 'Starting…');
    try {
      const { response, data } = await postJson('connect', { repo });
      if (response.status !== 202) {
        setResult(progress, 'error', data.message || 'Connecting the library failed.', data.detail);
        testedRepo = null;
        updateRepoDependentUi();
        return;
      }
      status.connectJob = data.connectJob;
      startPolling();
    } catch (error) {
      setResult(progress, 'error', `Connecting the library failed: ${error.message}`);
      updateRepoDependentUi();
    }
  }

  function startPolling() {
    if (polling) return;
    polling = setInterval(async () => {
      try {
        await fetchStatus();
      } catch {
        return; // transient; try again on the next tick
      }
      render();
      const job = status.connectJob;
      if (!job || job.status === 'running') return;
      clearInterval(polling);
      polling = null;
      if (job.status === 'succeeded') {
        setDismissed(false);
        if (job.warning) {
          el('library-setup-reload').classList.remove('hidden');
        } else {
          setTimeout(() => window.location.reload(), 1500);
        }
      } else {
        testedRepo = null;
        updateRepoDependentUi();
      }
    }, POLL_MS);
  }

  async function copyKey() {
    const textarea = el('library-setup-key');
    const button = el('library-setup-copy');
    let copied = false;
    try {
      if (navigator.clipboard && window.isSecureContext) {
        await navigator.clipboard.writeText(textarea.value);
        copied = true;
      }
    } catch { /* fall back below */ }
    if (!copied) {
      textarea.focus();
      textarea.select();
      try { copied = document.execCommand('copy'); } catch { copied = false; }
    }
    button.textContent = copied ? 'Copied' : 'Select and copy';
    setTimeout(() => { button.textContent = 'Copy'; }, 2000);
  }

  function renderSettingsEntry() {
    const section = el('library-sync-setup-section');
    if (!section) return;
    section.classList.remove('hidden');
    el('library-sync-disconnected').classList.toggle('hidden', !status.needsSetup);
    el('library-sync-connected').classList.toggle('hidden', status.needsSetup);
    el('library-sync-repo').textContent = status.repo || status.origin || 'a repository';
  }

  function setDisconnectBusy(busy) {
    ['library-sync-keep-btn', 'library-sync-clear-btn', 'library-sync-cancel-btn'].forEach((id) => {
      el(id).disabled = busy;
    });
  }

  async function disconnect(mode) {
    const repo = status.repo || 'this repository';
    const question = mode === 'clear'
      ? `Disconnect from ${repo} and remove every image from this add-on?\n\n` +
        'This is only done if everything is already on GitHub. The images stay in the repository.'
      : `Disconnect from ${repo}?\n\nThe library stays here and keeps working, without sync.`;
    if (!window.confirm(question)) return;

    const result = el('library-sync-disconnect-result');
    setDisconnectBusy(true);
    setResult(result, 'pending', mode === 'clear' ? 'Checking that everything is on GitHub…' : 'Disconnecting…');
    try {
      const { response, data } = await postJson('disconnect', { mode });
      if (response.ok && data.success) {
        setResult(result, 'success', `${data.message} Reloading…`);
        setTimeout(() => window.location.reload(), 1500);
        return;
      }
      setResult(result, 'error', data.message || 'Disconnecting failed.');
    } catch (error) {
      setResult(result, 'error', `Disconnecting failed: ${error.message}`);
    }
    setDisconnectBusy(false);
  }

  function bind() {
    el('library-setup-repo').addEventListener('input', () => {
      resetTest();
      renderConnection(); // the repository row compares the key with what is typed
    });
    el('library-setup-repo').addEventListener('keydown', (event) => {
      if (event.key === 'Enter' && !el('library-setup-test').disabled) testConnection();
    });
    el('library-setup-test').addEventListener('click', testConnection);
    el('library-setup-connect').addEventListener('click', connectLibrary);
    el('library-setup-copy').addEventListener('click', copyKey);
    el('library-setup-reload').addEventListener('click', () => window.location.reload());
    const later = () => {
      setDismissed(true);
      closeOverlay();
    };
    el('library-setup-later').addEventListener('click', later);
    el('library-setup-close').addEventListener('click', later);
    const panel = el('library-sync-disconnect-panel');
    el('library-sync-disconnect-btn').addEventListener('click', () => {
      setResult(el('library-sync-disconnect-result'), '', '');
      panel.classList.remove('hidden');
      el('library-sync-disconnect-btn').classList.add('hidden');
    });
    el('library-sync-cancel-btn').addEventListener('click', () => {
      panel.classList.add('hidden');
      el('library-sync-disconnect-btn').classList.remove('hidden');
    });
    el('library-sync-keep-btn').addEventListener('click', () => disconnect('keep'));
    ['library-setup-check-btn', 'library-sync-check-btn'].forEach((id) => {
      el(id).addEventListener('click', () => refreshConnection({ fresh: true }));
    });
    window.addEventListener('hashchange', () => {
      if (isSettingsTabShown() && status) refreshConnection();
    });
    el('library-sync-clear-btn').addEventListener('click', () => disconnect('clear'));
    const openBtn = el('open-library-setup-btn');
    if (openBtn) {
      openBtn.addEventListener('click', async () => {
        try { await fetchStatus(); } catch { /* keep the last status */ }
        if (!status) return;
        render();
        openOverlay();
      });
    }
  }

  async function init() {
    if (!el('library-setup')) return;
    bind();
    try {
      await fetchStatus();
    } catch (error) {
      console.warn('Library setup status unavailable:', error.message);
      return;
    }
    renderSettingsEntry();
    if (isSettingsTabShown()) refreshConnection();
    if (!status.needsSetup) return;
    render();
    if (isJobRunning()) {
      openOverlay();
      startPolling();
    } else if (status.canConnect && !status.hasLocalFiles && !isDismissed()) {
      openOverlay();
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
